#!/usr/bin/env python3
"""
Onboarding Agent — AI-Powered Customer Activation for First 30-90 Days
=======================================================================
Dedicated agent for the new-customer lifecycle.  Responsibilities:

  1. Analyse newly loaded customer data (industry, account count, KPI patterns)
  2. Generate a tailored **activation plan** (priority accounts, recommended playbooks)
  3. Set TTFV (Time to First Value) tracking baseline
  4. Auto-trigger Activation-Blitz playbook where appropriate
  5. Graduate account to Signal Analyst steady-state monitoring after TTFV

Provider-agnostic: works with OpenAI GPT-4o or Anthropic Claude.

Reuses:
  - AgentToolRegistry  (power_of_1_calc, health_score_calc, memory_remember, …)
  - AgentMemoryManager (MemoryScope.SHARED for cross-agent intelligence)
  - create_signal_analyst_agent() factory for LLM provider selection
  - CircuitBreaker from utils/; cost tracking via utils.llm_budget_controller.record_usage
"""

import json
import os
import sys
import time
import logging
from dataclasses import dataclass, field, asdict
from datetime import datetime, timedelta
from typing import Any, Dict, List, Optional

# Add parent directory for imports
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))

from utils.error_handling import CircuitBreaker
from utils.logging_config import initialize_logging
from utils.llm_budget_controller import record_usage as _llm_record_usage
from sqlalchemy import create_engine, text

logger = initialize_logging()


# ============================================================
# DATA CLASSES
# ============================================================

@dataclass
class ActivationPlanEntry:
    """A single account in the activation plan."""
    account_id: str
    account_name: str
    priority: str          # high / medium / low
    risk_level: str        # at_risk / healthy / expanding
    recommended_playbooks: List[str]
    ttfv_target_days: int  # Target days to first value
    rationale: str


@dataclass
class ActivationPlan:
    """Full activation plan generated by the Onboarding Agent."""
    customer_id: int
    customer_name: str
    industry: str
    total_accounts: int
    plan_entries: List[ActivationPlanEntry]
    global_recommendations: List[str]
    ttfv_baseline: Dict[str, Any]
    created_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())
    provider_used: str = "openai"
    generation_ms: int = 0


@dataclass
class TTFVStatus:
    """Time to First Value tracking for an account."""
    account_id: str
    onboarded_at: str
    ttfv_target_days: int
    current_day: int
    activation_score: float   # 0.0–1.0
    milestones_hit: List[str]
    is_graduated: bool = False
    graduated_at: Optional[str] = None



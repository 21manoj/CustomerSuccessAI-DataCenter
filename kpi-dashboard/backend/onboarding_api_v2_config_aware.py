    # ── Helper: resolve a signal_edges ref to a node_id for a given account ──
    import re as _re

    def _resolve_ref(ref: str, account_id: int):
        """Resolve a signal_edges ref string to a node_id.

        Ref formats:
          stakeholder:champion        → stakeholder_role_map['champion'][account_id]
          decision:dec_poc_approval    → decision_ref_map['dec_poc_approval'][account_id]
          outcome:out_expansion_deal   → outcome_ref_map['out_expansion_deal'][account_id]
          signal:phase1:w2             → signal_ref_map['phase1:w2'][account_id]
          phase1:w2 - GPU util...      → extract 'phase1:w2', lookup signal_ref_map
        """
        ref = ref.strip()
        if not ref:
            return None

        # stakeholder:<role>
        if ref.startswith('stakeholder:'):
            role = ref.split(':', 1)[1]
            return stakeholder_role_map.get(role, {}).get(account_id)

        # decision:<id>
        if ref.startswith('decision:'):
            did = ref.split(':', 1)[1]
            return decision_ref_map.get(did, {}).get(account_id)

        # outcome:<id>
        if ref.startswith('outcome:'):
            oid = ref.split(':', 1)[1]
            return outcome_ref_map.get(oid, {}).get(account_id)

        # signal:phase1:w2  (prefixed)
        if ref.startswith('signal:'):
            sref = ref.split(':', 1)[1]  # "phase1:w2"
            return signal_ref_map.get(sref, {}).get(account_id)

        # phase1:w2 - description  (causal chain format)
        m = _re.match(r'(phase\d+:w\d+)', ref)
        if m:
            sref = m.group(1)
            return signal_ref_map.get(sref, {}).get(account_id)

        # bare sig_XXXX_N or narrative_sig_XXXX_N  (V3 driver format)
        if ref.startswith('sig_') or ref.startswith('narrative_sig_'):
            return signal_ref_map.get(ref, {}).get(account_id)

        # bare dec_XXXX_N  (V3 driver format without decision: prefix)
        if ref.startswith('dec_'):
            return decision_ref_map.get(ref, {}).get(account_id)

        # outcome by outcome_type fallback (e.g. "revenue_at_risk")
        nid = outcome_ref_map.get(ref, {}).get(account_id)
        if nid:
            return nid

        # Phased / recovery / CSM-action signal_ref keys (e.g. intervention_sig_415001_1,
        # baseline_narrative_sig_*, intervention_recovery_*). Prior narrow checks miss these.
        nid = signal_ref_map.get(ref, {}).get(account_id)
        if nid:
            return nid

        return None

    # ── 8. signal_edges.csv → context_edges (with ref resolution) ──
    edges_file = data_dir / 'signal_edges.csv'
    if edges_file.exists():
        try:
            df = pd.read_csv(edges_file)
            unresolved = 0
            with engine.begin() as conn:
                for _, row in df.iterrows():
                    from_ref = str(row.get('from_signal_ref', ''))
                    to_ref = str(row.get('to_signal_ref', ''))
                    rev_impact = None
                    try:
                        rev_impact = float(row.get('revenue_impact', 0))
                    except (ValueError, TypeError):
                        pass

                    props = _sanitize_props({
                        'from_signal_ref': from_ref,
                        'to_signal_ref': to_ref,
                        'evidence': row.get('evidence', ''),
                        'created_by': row.get('created_by', 'csv_import'),
                    })

                    _raw_etype = row.get('edge_type', 'CORRELATES_WITH')
                    if _raw_etype is None or (isinstance(_raw_etype, float) and pd.isna(_raw_etype)):
                        edge_type = 'CORRELATES_WITH'
                    else:
                        edge_type = str(_raw_etype).strip()

                    # If row has a specific account_id, resolve for that account only.
                    # Otherwise (arc-level edges), replicate for each account.
                    row_acct_id = None
                    for _col in ('account_id', 'source_account_id'):
                        _v = row.get(_col)
                        if _v is not None and not (isinstance(_v, float) and pd.isna(_v)):
                            try:
                                row_acct_id = int(float(_v))
                                break
                            except (ValueError, TypeError):
                                pass
                    acct_ids_to_resolve = [row_acct_id] if row_acct_id else sorted(all_account_ids)

                    for acct_id in acct_ids_to_resolve:
                        from_nid = _resolve_ref(from_ref, acct_id)
                        to_nid = _resolve_ref(to_ref, acct_id)

                        if from_nid and to_nid:
                            # ── Temporal validation: skip backward causal edges ──
                            if edge_type in ('LED_TO', 'TRIGGERED', 'CAUSED_BY'):
                                from_row = conn.execute(text(
                                    "SELECT occurred_at FROM context_nodes WHERE node_id = :nid"
                                ), {'nid': from_nid}).fetchone()
                                to_row = conn.execute(text(
                                    "SELECT occurred_at FROM context_nodes WHERE node_id = :nid"
                                ), {'nid': to_nid}).fetchone()
                                if (from_row and to_row
                                        and from_row[0] is not None and to_row[0] is not None
                                        and from_row[0] > to_row[0]):
                                    current_app.logger.warning(
                                        f"signal_edges: skipping backward {edge_type} edge "
                                        f"({from_row[0]} → {to_row[0]}) "
                                        f"(from_ref={from_ref!r} to_ref={to_ref!r})"
                                    )
                                    continue

                            conn.execute(text("""
                                INSERT INTO context_edges
                                    (customer_id, from_node_id, to_node_id,
                                     edge_type, weight, confidence,
                                     lag_days, revenue_impact, properties, source_platform)
                                VALUES
                                    (:cid, :from_nid, :to_nid,
                                     :etype, :weight, :conf,
                                     :lag, :rev, :props, :src)
                            """), {
                                'cid': customer_id,
                                'from_nid': from_nid,
                                'to_nid': to_nid,
                                'etype': edge_type,
                                'weight': float(row.get('weight', 0.5)),
                                'conf': float(row.get('confidence', 0.5)),
                                'lag': int(row.get('lag_days', 0)),
                                'rev': rev_impact,
                                'props': json.dumps(props),
                                'src': row.get('source_platform', 'csv_import'),
                            })
                            result['edges_inserted'] += 1
                        else:
                            unresolved += 1

            if unresolved:
                current_app.logger.warning(
                    f"signal_edges: {unresolved} edge-account pairs could not be resolved"
                )
            result['files_loaded'].append('signal_edges.csv')
            current_app.logger.info(
                f"✅ Loaded {result['edges_inserted']} signal edges "
                f"({len(df)} rows × {len(all_account_ids)} accounts, {unresolved} unresolved)"
            )
        except Exception as e:
            result['errors'].append(f"signal_edges.csv: {str(e)}")
            current_app.logger.error(f"Error loading signal_edges.csv: {e}", exc_info=True)

    # NOTE: SOURCED_FROM edges are now included in signal_edges.csv.
    # merged into signal_edges.csv by _auto_generate_context_graph_files() before
    # this function is called.

    return result



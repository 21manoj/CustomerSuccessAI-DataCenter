def _auto_generate_involves_edges(customer_id: int, account_ids: list) -> int:
    """
    Auto-generate INVOLVES edges between STAKEHOLDER and DECISION nodes.

    For each DECISION node that has a `decision_maker_role` property, find
    STAKEHOLDER nodes in the same account whose node_subtype or title matches
    the role, and create an INVOLVES edge.

    Returns the number of edges created.
    """
    from models import ContextNode, ContextEdge

    if not account_ids:
        return 0

    # Get all decision nodes with decision_maker_role
    decisions = ContextNode.query.filter(
        ContextNode.customer_id == customer_id,
        ContextNode.account_id.in_(account_ids),
        ContextNode.node_type == 'DECISION',
    ).all()

    # Get all stakeholder nodes
    stakeholders = ContextNode.query.filter(
        ContextNode.customer_id == customer_id,
        ContextNode.account_id.in_(account_ids),
        ContextNode.node_type == 'STAKEHOLDER',
    ).all()

    # Build stakeholder lookup: account_id → [stakeholder_nodes]
    stakeholder_by_account = {}
    for s in stakeholders:
        stakeholder_by_account.setdefault(s.account_id, []).append(s)

    # Check existing INVOLVES edges to avoid duplicates
    existing_involves = set()
    existing_edges = ContextEdge.query.filter(
        ContextEdge.customer_id == customer_id,
        ContextEdge.edge_type == 'INVOLVES',
    ).all()
    for e in existing_edges:
        existing_involves.add((e.from_node_id, e.to_node_id))

    created = 0
    for dec in decisions:
        props = dec.properties or {}
        maker_role = props.get('decision_maker_role', '')
        if not maker_role:
            continue

        maker_lower = maker_role.lower().strip()
        account_stakeholders = stakeholder_by_account.get(dec.account_id, [])

        for stk in account_stakeholders:
            # Match by subtype (role) or by title containing the role
            stk_subtype = (stk.node_subtype or '').lower()
            stk_title = (stk.title or '').lower()

            match = (
                maker_lower == stk_subtype
                or maker_lower in stk_title
                or stk_subtype in maker_lower
                # Fuzzy: "vp_operations" matches "VP of Operations"
                or maker_lower.replace('_', ' ') in stk_title
            )

            if match and (stk.node_id, dec.node_id) not in existing_involves:
                edge = ContextEdge(
                    customer_id=customer_id,
                    from_node_id=stk.node_id,
                    to_node_id=dec.node_id,
                    edge_type='INVOLVES',
                    weight=0.85,
                    confidence=0.8,
                    properties={
                        'role': maker_role,
                        'auto_generated': True,
                        'match_type': 'decision_maker_role',
                    },
                )
                db.session.add(edge)
                existing_involves.add((stk.node_id, dec.node_id))
                created += 1

    return created


def _auto_generate_context_graph_files(customer_id: int, cg_data_dir: Path, data_dir: Path, engine):
    """
    Auto-generate 2 platform-derived context graph CSVs (decisions, signal_edges)
    and seed 1 curated benchmark file (industry_benchmarks) if not uploaded.
    Files are written to cg_data_dir so that ingest_context_graph_csvs picks
    them up normally.

    Generated files are stored at:
      verticals/customer{id}-dc2_s/data/context_graph/{filename}
    """
    from sqlalchemy import text

    cg_data_dir.mkdir(parents=True, exist_ok=True)

    # ── 1. decisions.csv — inferred from outcomes + stakeholder data ──
    decisions_file = cg_data_dir / 'decisions.csv'
    if not decisions_file.exists():
        try:
            current_app.logger.info(f"Auto-generating decisions.csv for customer {customer_id}...")
            outcomes_file = cg_data_dir / 'outcomes.csv'
            if not outcomes_file.exists():
                outcomes_file = data_dir / 'outcomes.csv'

            if outcomes_file.exists():
                df_outcomes = pd.read_csv(outcomes_file)
                decisions_rows = []
                for _, row in df_outcomes.iterrows():
                    account_id = row.get('account_id')
                    outcome_type = str(row.get('outcome_type', 'unknown'))
                    outcome_date = row.get('outcome_date', '')
                    title = row.get('title', '')
                    revenue = row.get('revenue_impact', row.get('revenue_value', 0))

                    # Infer a decision that led to this outcome
                    decision_map = {
                        'expansion': ('Approve expansion deal', 'executive_sponsor', 'proceed_with_expansion'),
                        'churn': ('Retention intervention decision', 'csm', 'escalate_to_exec'),
                        'contraction': ('Budget reallocation decision', 'economic_buyer', 'reduce_scope'),
                        'renewal': ('Renewal approval', 'economic_buyer', 'renew_contract'),
                        'upsell': ('Upsell opportunity decision', 'champion', 'approve_upsell'),
                    }
                    mapped = decision_map.get(outcome_type.lower(), (
                        f'Decision for {outcome_type}', 'csm', outcome_type.lower()
                    ))

                    decisions_rows.append({
                        'account_id': account_id,
                        'decision_date': outcome_date,
                        'title': mapped[0],
                        'decision_maker_role': mapped[1],
                        'chosen_option': mapped[2],
                        'decision_id': f'dec_auto_{outcome_type}_{account_id}',
                        'revenue_impact': revenue,
                        'risk_level': 'high' if outcome_type.lower() in ('churn', 'contraction') else 'medium',
                        'confidence': 0.7,
                    })

                if decisions_rows:
                    pd.DataFrame(decisions_rows).to_csv(decisions_file, index=False)
                    current_app.logger.info(f"✅ Auto-generated decisions.csv ({len(decisions_rows)} rows) at {decisions_file}")
                else:
                    current_app.logger.info("No outcomes data to derive decisions from — skipping decisions.csv auto-generation")
            else:
                current_app.logger.info("No outcomes.csv found — skipping decisions.csv auto-generation")
        except Exception as e:
            current_app.logger.warning(f"Could not auto-generate decisions.csv: {e}")

    # ── 2. signal_edges.csv — derived from temporal correlation between signals ──
    edges_file = cg_data_dir / 'signal_edges.csv'
    if not edges_file.exists():
        try:
            current_app.logger.info(f"Auto-generating signal_edges.csv for customer {customer_id}...")
            # Build edges from: engagement_events → outcomes (LED_TO),
            # stakeholder engagement → decisions (INFLUENCED), decisions → outcomes (LED_TO)
            edges_rows = []

            # If we have engagement_events and outcomes, create temporal LED_TO edges
            eng_file = cg_data_dir / 'engagement_events.csv'
            if not eng_file.exists():
                eng_file = data_dir / 'engagement_events.csv'
            outcomes_file = cg_data_dir / 'outcomes.csv'
            if not outcomes_file.exists():
                outcomes_file = data_dir / 'outcomes.csv'

            # Decision→Outcome edges (SOURCED_FROM / LED_TO)
            dec_file = cg_data_dir / 'decisions.csv'
            if dec_file.exists() and outcomes_file.exists():
                df_dec = pd.read_csv(dec_file)
                df_out = pd.read_csv(outcomes_file)
                for _, dec_row in df_dec.iterrows():
                    dec_ref = dec_row.get('decision_id', '')
                    dec_acct = dec_row.get('account_id')
                    # Find outcomes for same account
                    acct_outcomes = df_out[df_out['account_id'] == dec_acct] if not df_out.empty else pd.DataFrame()
                    for _, out_row in acct_outcomes.iterrows():
                        out_ref = out_row.get('outcome_id', f"outcome:{out_row.get('title', 'unknown')}")
                        edges_rows.append({
                            'from_signal_ref': f'decision:{dec_ref}',
                            'to_signal_ref': f'outcome:{out_ref}',
                            'edge_type': 'LED_TO',
                            'weight': 0.8,
                            'confidence': 0.7,
                            'lag_days': 30,
                            'revenue_impact': out_row.get('revenue_impact', row.get('revenue_value', 0)),
                            'evidence': f'Decision {dec_ref} led to outcome',
                            'created_by': 'auto_generation',
                        })

            # Stakeholder→Decision edges (INFLUENCED)
            stk_file = cg_data_dir / 'stakeholders.csv'
            if not stk_file.exists():
                stk_file = data_dir / 'stakeholders.csv'
            if stk_file.exists() and dec_file.exists():
                df_stk = pd.read_csv(stk_file)
                df_dec = pd.read_csv(dec_file)
                for _, dec_row in df_dec.iterrows():
                    dec_ref = dec_row.get('decision_id', '')
                    maker_role = dec_row.get('decision_maker_role', '')
                    dec_acct = dec_row.get('account_id')
                    # Find stakeholder matching the decision maker role
                    matching = df_stk[(df_stk['account_id'] == dec_acct) & (df_stk['role'].str.lower() == str(maker_role).lower())]
                    for _, stk_row in matching.iterrows():
                        stk_name = stk_row.get('stakeholder_name', '')
                        edges_rows.append({
                            'from_signal_ref': f'stakeholder:{stk_row.get("role", "unknown")}',
                            'to_signal_ref': f'decision:{dec_ref}',
                            'edge_type': 'INFLUENCED',
                            'weight': float(stk_row.get('influence_score', 0.5)),
                            'confidence': 0.6,
                            'lag_days': 0,
                            'evidence': f'{stk_name} influenced decision as {maker_role}',
                            'created_by': 'auto_generation',
                        })

            if edges_rows:
                pd.DataFrame(edges_rows).to_csv(edges_file, index=False)
                current_app.logger.info(f"✅ Auto-generated signal_edges.csv ({len(edges_rows)} rows) at {edges_file}")
            else:
                current_app.logger.info("Insufficient data to derive signal edges — skipping signal_edges.csv auto-generation")
        except Exception as e:
            current_app.logger.warning(f"Could not auto-generate signal_edges.csv: {e}")

    # ── 3. industry_benchmarks.csv — from platform-curated seed file per vertical ──
    # NOT auto-generated from KPI targets (that's circular). Instead, we ship curated
    # benchmark files per vertical in config/industry_benchmarks/{vertical}.csv,
    # seeded via LLM + industry research, then curated by domain experts.
    benchmarks_file = cg_data_dir / 'industry_benchmarks.csv'
    if not benchmarks_file.exists():
        try:
            # Determine vertical from customer config or directory structure
            vertical = 'dc2_s'  # default
            try:
                from sqlalchemy import text as sa_text
                with engine.connect() as conn:
                    v = conn.execute(sa_text(
                        "SELECT vertical FROM customers WHERE id = :cid"
                    ), {'cid': customer_id}).scalar()
                    if v:
                        vertical = v
            except Exception:
                pass  # fall back to dc2_s
            seed_file = Path(__file__).parent / 'config' / 'industry_benchmarks' / f'{vertical}.csv'

            if seed_file.exists():
                current_app.logger.info(f"Seeding industry_benchmarks.csv from curated {vertical} benchmarks...")
                df_seed = pd.read_csv(seed_file)

                # Map curated seed columns to the ingestion-expected format
                benchmarks_rows = []
                for _, row in df_seed.iterrows():
                    benchmarks_rows.append({
                        'kpi_code': row.get('kpi_code', ''),
                        'kpi_name': row.get('kpi_name', ''),
                        'pillar': row.get('pillar', ''),
                        'unit': row.get('unit', ''),
                        'benchmark_source': row.get('source', 'platform_curated'),
                        'industry_p25': row.get('p25', 0),
                        'industry_p50': row.get('p50', 0),
                        'industry_p75': row.get('p75', 0),
                        'industry_p90': row.get('p90', 0),
                        'methodology': row.get('methodology', ''),
                        'benchmark_date': row.get('last_updated', datetime.utcnow().strftime('%Y-%m-%d')),
                        'curated': row.get('curated', False),
                    })

                if benchmarks_rows:
                    pd.DataFrame(benchmarks_rows).to_csv(benchmarks_file, index=False)
                    curated_count = sum(1 for r in benchmarks_rows if str(r.get('curated', '')).lower() == 'true')
                    current_app.logger.info(
                        f"✅ Seeded industry_benchmarks.csv ({len(benchmarks_rows)} rows, "
                        f"{curated_count} curated) from {seed_file.name}"
                    )
                else:
                    current_app.logger.info(f"Seed file {seed_file.name} is empty — skipping industry_benchmarks.csv")
            else:
                current_app.logger.warning(
                    f"No curated benchmark seed file found at {seed_file} — "
                    f"skipping industry_benchmarks.csv. Upload manually or add seed file."
                )
        except Exception as e:
            current_app.logger.warning(f"Could not seed industry_benchmarks.csv: {e}")

    # decision_evidence.csv migration removed March 2026 — use signal_edges.csv directly


# ============================================================================
# Context Graph Ingestion (7 CSVs → context_nodes + context_edges)
# 4 customer-provided + 3 auto-generated by platform
# ============================================================================

def ingest_context_graph_csvs(customer_id: int, data_dir: Path, engine) -> Dict[str, Any]:
    """
    Ingest 7 context graph CSVs into context_nodes and context_edges tables.
    Only called when the context_graph feature toggle is ON for this customer.

    Returns dict with counts and any errors encountered.
    """
    from sqlalchemy import text
    import pandas as pd

    result = {'nodes_inserted': 0, 'edges_inserted': 0, 'files_loaded': [], 'errors': []}

    # Helper: upsert a context node and return the node_id
    def _clean_val(v):
        """Convert pandas NaN/NaT to None for PostgreSQL compatibility."""
        import math
        if v is None or v is pd.NaT:
            return None
        if isinstance(v, float) and math.isnan(v):
            return None
        return v

    def _sanitize_props(props):
        """Replace pandas NaN/NaT values with None for valid JSON serialization."""
        if not props:
            return props
        return {k: _clean_val(v) for k, v in props.items()}

    def _insert_node(conn, customer_id, account_id, node_type, node_subtype,
                     label, properties, tier=1, source_platform='csv_import',
                     source_event_id=None, event_time=None,
                     revenue_impact=None, revenue_impact_type=None,
                     source='customer'):
        # occurred_at is NOT NULL — always provide a value
        resolved_etime = _clean_val(event_time) or datetime.utcnow().strftime('%Y-%m-%d')
        row = conn.execute(text("""
            INSERT INTO context_nodes
                (customer_id, account_id, node_type, node_subtype, title,
                 properties, tier, source_platform, source_event_id,
                 occurred_at, revenue_impact, revenue_impact_type, source)
            VALUES
                (:cid, :aid, :ntype, :nsub, :title,
                 :props, :tier, :src, :src_eid,
                 :etime, :rev, :rev_type, :node_source)
            RETURNING node_id
        """), {
            'cid': customer_id, 'aid': int(account_id),
            'ntype': node_type, 'nsub': _clean_val(node_subtype),
            'title': label, 'props': json.dumps(_sanitize_props(properties)) if properties else None,
            'tier': tier, 'src': _clean_val(source_platform), 'src_eid': _clean_val(source_event_id),
            'etime': resolved_etime, 'rev': _clean_val(revenue_impact),
            'rev_type': _clean_val(revenue_impact_type), 'node_source': source
        })
        return row.scalar()

    # --- Clear existing context graph data for this customer (idempotent) ---
    try:
        with engine.begin() as conn:
            # Delete edges by customer_id (covers both resolved and NULL node refs)
            conn.execute(text("""
                DELETE FROM context_edges WHERE customer_id = :cid
            """), {'cid': customer_id})
            conn.execute(text("""
                DELETE FROM context_nodes WHERE customer_id = :cid
            """), {'cid': customer_id})
            current_app.logger.info(f"Cleared existing context graph data for customer {customer_id}")
    except Exception as e:
        current_app.logger.warning(f"Could not clear old context graph data: {e}")

    # ── Ref→node_id lookup maps (populated during ingestion, used for edge resolution) ──
    # stakeholder_role_map: role → {account_id → node_id}
    # decision_ref_map: decision_id → {account_id → node_id}
    # outcome_ref_map: outcome_id → {account_id → node_id}
    # signal_ref_map: signal_ref → {account_id → node_id}
    stakeholder_role_map = {}
    decision_ref_map = {}
    outcome_ref_map = {}
    signal_ref_map = {}
    all_account_ids = set()

    # ── 1. stakeholders.csv → STAKEHOLDER nodes ──
    stakeholders_file = data_dir / 'stakeholders.csv'
    if stakeholders_file.exists():
        try:
            df = pd.read_csv(stakeholders_file)
            with engine.begin() as conn:
                for _, row in df.iterrows():
                    account_id_val = int(row['account_id'])
                    all_account_ids.add(account_id_val)
                    role = row.get('role', 'end_user')
                    props = {
                        'email': row.get('email', ''),
                        'engagement_frequency': row.get('engagement_frequency', ''),
                        'department': row.get('department', ''),
                        'is_active': row.get('is_active', True),
                    }
                    nid = _insert_node(
                        conn, customer_id, account_id_val,
                        'STAKEHOLDER', role,
                        f"{row['stakeholder_name']} ({row['title']})",
                        props, tier=1, source_platform=row.get('source_platform', 'csv_import'),
                        event_time=row.get('first_observed_at'),
                    )
                    stakeholder_role_map.setdefault(role, {})[account_id_val] = nid
                    result['nodes_inserted'] += 1
            result['files_loaded'].append('stakeholders.csv')
            current_app.logger.info(f"✅ Loaded {len(df)} stakeholder nodes")
        except Exception as e:
            result['errors'].append(f"stakeholders.csv: {str(e)}")
            current_app.logger.error(f"Error loading stakeholders.csv: {e}", exc_info=True)

    # ── 2. engagement_events.csv → SIGNAL nodes (subtype=engagement) ──
    events_file = data_dir / 'engagement_events.csv'
    if events_file.exists():
        try:
            df = pd.read_csv(events_file)
            with engine.begin() as conn:
                for idx, row in df.iterrows():
                    account_id_val = int(row['account_id'])
                    all_account_ids.add(account_id_val)
                    props = {
                        'channel': row.get('channel', ''),
                        'duration_minutes': row.get('duration_minutes', 0),
                        'outcome': row.get('outcome', ''),
                        'stakeholder_name': row.get('stakeholder_name', ''),
                        'sentiment_shift': row.get('sentiment_shift', 0),
                    }
                    _insert_node(
                        conn, customer_id, account_id_val,
                        'SIGNAL', 'engagement',
                        row.get('description', '')[:200],
                        props, tier=2,
                        event_time=row.get('event_date'),
                        source_platform=row.get('source_platform', 'csv_import'),
                    )
                    result['nodes_inserted'] += 1
            result['files_loaded'].append('engagement_events.csv')
            current_app.logger.info(f"✅ Loaded {len(df)} engagement event nodes")
        except Exception as e:
            result['errors'].append(f"engagement_events.csv: {str(e)}")
            current_app.logger.error(f"Error loading engagement_events.csv: {e}", exc_info=True)

    # ── 3. account_business_profiles.csv → ACCOUNT nodes ──
    profiles_file = data_dir / 'account_business_profiles.csv'
    if profiles_file.exists():
        try:
            df = pd.read_csv(profiles_file)
            with engine.begin() as conn:
                for _, row in df.iterrows():
                    props = {
                        'arr': row.get('arr', 0),
                        'employee_count': row.get('employee_count', 0),
                        'fiscal_year_end': row.get('fiscal_year_end', ''),
                        'tech_stack': row.get('tech_stack', ''),
                        'cloud_provider': row.get('cloud_provider', ''),
                        'competitive_landscape': row.get('competitive_landscape', ''),
                        'strategic_initiatives': row.get('strategic_initiatives', ''),
                        'budget_cycle': row.get('budget_cycle', ''),
                    }
                    _insert_node(
                        conn, customer_id, row['account_id'],
                        'ACCOUNT', 'business_profile',
                        f"Account {row['account_id']} - {row.get('industry', '')}",
                        props, tier=1,
                        event_time=row.get('profile_date'),
                    )
                    result['nodes_inserted'] += 1
            result['files_loaded'].append('account_business_profiles.csv')
            current_app.logger.info(f"✅ Loaded {len(df)} account business profile nodes")
        except Exception as e:
            result['errors'].append(f"account_business_profiles.csv: {str(e)}")
            current_app.logger.error(f"Error loading account_business_profiles.csv: {e}", exc_info=True)

    # ── 4. decisions.csv → DECISION nodes ──
    decisions_file = data_dir / 'decisions.csv'
    if decisions_file.exists():
        try:
            df = pd.read_csv(decisions_file)
            with engine.begin() as conn:
                for idx, row in df.iterrows():
                    account_id_val = int(row['account_id'])
                    all_account_ids.add(account_id_val)
                    decision_id = str(row.get('decision_id', '')).strip()
                    props = {
                        'decision_id': decision_id,
                        'decision_maker_role': row.get('decision_maker_role', ''),
                        'chosen_option': row.get('chosen_option', ''),
                        'options_considered': row.get('options_considered', ''),
                        'risk_level': row.get('risk_level', 'medium'),
                        'evidence_refs': row.get('evidence_refs', ''),
                        'outcome_description': row.get('outcome_description', ''),
                    }
                    rev_impact = None
                    try:
                        rev_impact = float(row.get('revenue_impact', 0))
                    except (ValueError, TypeError):
                        pass
                    nid = _insert_node(
                        conn, customer_id, account_id_val,
                        'DECISION', row.get('risk_level', 'medium'),
                        row.get('title', '')[:200],
                        props, tier=1,
                        event_time=row.get('decision_date'),
                        revenue_impact=rev_impact,
                        revenue_impact_type='at_risk' if (rev_impact and rev_impact < 0) else 'protected',
                        source_event_id=decision_id or f"decision_{idx}",
                    )
                    if decision_id:
                        decision_ref_map.setdefault(decision_id, {})[account_id_val] = nid
                        # Also index by stripped-prefix version for backward compat
                        for _pfx in ('baseline_', 'intervention_',
                                     'baseline_auto_', 'intervention_auto_'):
                            if decision_id.startswith(_pfx):
                                _bare = decision_id[len(_pfx):]
                                decision_ref_map.setdefault(_bare, {})[account_id_val] = nid
                                break
                    result['nodes_inserted'] += 1
            result['files_loaded'].append('decisions.csv')
            current_app.logger.info(f"✅ Loaded {len(df)} decision nodes")
        except Exception as e:
            result['errors'].append(f"decisions.csv: {str(e)}")
            current_app.logger.error(f"Error loading decisions.csv: {e}", exc_info=True)

    # ── 5. outcomes.csv → OUTCOME nodes ──
    outcomes_file = data_dir / 'outcomes.csv'
    if outcomes_file.exists():
        try:
            df = pd.read_csv(outcomes_file)
            with engine.begin() as conn:
                for _, row in df.iterrows():
                    account_id_val = int(row['account_id'])
                    all_account_ids.add(account_id_val)
                    outcome_id = str(row.get('outcome_id', '')).strip()
                    rev_val = None
                    try:
                        rev_val = float(row.get('revenue_impact', row.get('revenue_value', 0)))
                    except (ValueError, TypeError):
                        pass
                    outcome_type = row.get('outcome_type', 'retention')
                    rev_type_map = {
                        'expansion': 'expansion', 'expansion_approved': 'expansion',
                        'retention': 'protected', 'revenue_protected': 'protected',
                        'churn_averted': 'protected', 'renewal_secured': 'protected',
                        'engagement_recovery': 'protected', 'cost_reduction': 'protected',
                        'churn_loss': 'lost', 'revenue_at_risk': 'at_risk',
                        'engagement_decline': 'at_risk', 'renewal_uncertainty': 'at_risk',
                        'capacity_constraint': 'at_risk', 'partner_friction': 'at_risk',
                        'revenue_growth': 'expansion',
                    }
                    props = {
                        'outcome_id': outcome_id,
                        'evidence': row.get('evidence', ''),
                        'related_decision_id': row.get('related_decision_id', ''),
                    }
                    nid = _insert_node(
                        conn, customer_id, account_id_val,
                        'OUTCOME', outcome_type,
                        row.get('title', '')[:200],
                        props, tier=1,
                        event_time=row.get('outcome_date'),
                        revenue_impact=rev_val,
                        revenue_impact_type=rev_type_map.get(outcome_type, 'none'),
                        source_platform=row.get('source_platform', 'csv_import'),
                    )
                    if outcome_id:
                        outcome_ref_map.setdefault(outcome_id, {})[account_id_val] = nid
                    # Also register by outcome_type for V3 driver refs like "outcome:revenue_at_risk"
                    if outcome_type:
                        outcome_ref_map.setdefault(outcome_type, {})[account_id_val] = nid
                    result['nodes_inserted'] += 1
            result['files_loaded'].append('outcomes.csv')
            current_app.logger.info(f"✅ Loaded {len(df)} outcome nodes")
        except Exception as e:
            result['errors'].append(f"outcomes.csv: {str(e)}")
            current_app.logger.error(f"Error loading outcomes.csv: {e}", exc_info=True)

    # ── 6. industry_benchmarks.csv → EXTERNAL_CONTEXT nodes ──
    benchmarks_file = data_dir / 'industry_benchmarks.csv'
    if benchmarks_file.exists():
        try:
            df = pd.read_csv(benchmarks_file)
            # Benchmarks are global, not per-account; use first account of customer
            with engine.begin() as conn:
                first_acc = conn.execute(text(
                    "SELECT account_id FROM accounts WHERE customer_id = :cid ORDER BY account_id LIMIT 1"
                ), {'cid': customer_id}).scalar()
                if first_acc:
                    for _, row in df.iterrows():
                        props = {
                            'benchmark_source': row.get('benchmark_source', row.get('source', '')),
                            'industry_p25': row.get('industry_p25', row.get('p25', 0)),
                            'industry_p50': row.get('industry_p50', row.get('p50', 0)),
                            'industry_p75': row.get('industry_p75', row.get('p75', 0)),
                            'industry_p90': row.get('industry_p90', row.get('p90', 0)),
                            'account_percentile': row.get('account_percentile', 50),
                            'methodology': row.get('methodology', ''),
                            'curated': str(row.get('curated', False)),
                            'unit': row.get('unit', ''),
                            'pillar': row.get('pillar', ''),
                            'benchmark_date': row.get('benchmark_date', row.get('last_updated', '')),
                        }
                        kpi_code = row.get('kpi_code', '')
                        kpi_name = row.get('kpi_name', kpi_code)
                        _insert_node(
                            conn, customer_id, first_acc,
                            'EXTERNAL_CONTEXT', 'industry_benchmark',
                            f"Benchmark: {kpi_code} — {kpi_name}",
                            props, tier=1,
                            source_event_id=f"bench_{kpi_code}",
                            event_time=row.get('benchmark_date', row.get('last_updated')),
                        )
                        result['nodes_inserted'] += 1
            result['files_loaded'].append('industry_benchmarks.csv')
            current_app.logger.info(f"✅ Loaded {len(df)} benchmark nodes")
        except Exception as e:
            result['errors'].append(f"industry_benchmarks.csv: {str(e)}")
            current_app.logger.error(f"Error loading industry_benchmarks.csv: {e}", exc_info=True)

    # ── 7. enhanced_qualitative_signals.csv → SIGNAL nodes (with graph metadata) ──
    # File may be in context_graph/ or parent data/ directory
    enhanced_file = data_dir / 'enhanced_qualitative_signals.csv'
    if not enhanced_file.exists():
        enhanced_file = data_dir.parent / 'enhanced_qualitative_signals.csv'
    if enhanced_file.exists():
        try:
            df = pd.read_csv(enhanced_file)
            with engine.begin() as conn:
                for idx, row in df.iterrows():
                    account_id_val = int(row['account_id'])
                    all_account_ids.add(account_id_val)
                    sig_ref = str(row.get('signal_ref', '')).strip()
                    props = {
                        'signal_ref': sig_ref,
                        'signal_type': row.get('signal_type', 'signal'),
                        'sentiment': row.get('sentiment', 'neutral'),
                        'sentiment_score': row.get('sentiment_score', 0),
                        'stakeholder_name': row.get('stakeholder_name', ''),
                        'stakeholder_title': row.get('stakeholder_title', ''),
                        'causal_chain_ref': row.get('causal_chain_ref', ''),
                    }
                    # Revenue impact is intentionally NOT stored on SIGNAL
                    # nodes — it belongs exclusively on OUTCOME nodes to
                    # prevent double-counting across the causal chain.
                    nid = _insert_node(
                        conn, customer_id, account_id_val,
                        'SIGNAL', row.get('signal_type', 'signal'),
                        str(row.get('content', ''))[:200],
                        props, tier=2,
                        event_time=row.get('signal_date'),
                        revenue_impact=None,
                        source_platform=row.get('source_platform', 'csv_import'),
                    )
                    if sig_ref:
                        signal_ref_map.setdefault(sig_ref, {})[account_id_val] = nid
                        # Also index by stripped-prefix version so signal_edges.csv
                        # generated without phase prefix still resolves (e.g. old
                        # signal_edges.csv has 'sig_424001_1' but signals file has
                        # 'baseline_sig_424001_1').
                        for _pfx in ('baseline_', 'intervention_',
                                     'baseline_narrative_', 'intervention_narrative_',
                                     'baseline_recovery_', 'intervention_recovery_',
                                     'baseline_csm_action_', 'intervention_csm_action_',
                                     'baseline_auto_recovery_', 'intervention_auto_recovery_'):
                            if sig_ref.startswith(_pfx):
                                _bare = sig_ref[len(_pfx):]
                                signal_ref_map.setdefault(_bare, {})[account_id_val] = nid
                                break
                    result['nodes_inserted'] += 1
            result['files_loaded'].append('enhanced_qualitative_signals.csv')
            current_app.logger.info(f"✅ Loaded {len(df)} enhanced signal nodes")
        except Exception as e:
            result['errors'].append(f"enhanced_qualitative_signals.csv: {str(e)}")
            current_app.logger.error(f"Error loading enhanced_qualitative_signals.csv: {e}", exc_info=True)

    # ── Helper: resolve a signal_edges ref to a node_id for a given account ──
    import re as _re

    def _resolve_ref(ref: str, account_id: int):
        """Resolve a signal_edges ref string to a node_id.

        Ref formats:
          stakeholder:champion        → stakeholder_role_map['champion'][account_id]
          decision:dec_poc_approval    → decision_ref_map['dec_poc_approval'][account_id]
          outcome:out_expansion_deal   → outcome_ref_map['out_expansion_deal'][account_id]
          signal:phase1:w2             → signal_ref_map['phase1:w2'][account_id]
          phase1:w2 - GPU util...      → extract 'phase1:w2', lookup signal_ref_map
        """
        ref = ref.strip()
        if not ref:
            return None

        # stakeholder:<role>
        if ref.startswith('stakeholder:'):
            role = ref.split(':', 1)[1]
            return stakeholder_role_map.get(role, {}).get(account_id)

        # decision:<id>
        if ref.startswith('decision:'):
            did = ref.split(':', 1)[1]
            return decision_ref_map.get(did, {}).get(account_id)

        # outcome:<id>
        if ref.startswith('outcome:'):
            oid = ref.split(':', 1)[1]
            return outcome_ref_map.get(oid, {}).get(account_id)

        # signal:phase1:w2  (prefixed)
        if ref.startswith('signal:'):
            sref = ref.split(':', 1)[1]  # "phase1:w2"
            return signal_ref_map.get(sref, {}).get(account_id)

        # phase1:w2 - description  (causal chain format)
        m = _re.match(r'(phase\d+:w\d+)', ref)
        if m:
            sref = m.group(1)
            return signal_ref_map.get(sref, {}).get(account_id)

        # bare sig_XXXX_N or narrative_sig_XXXX_N  (V3 driver format)
        if ref.startswith('sig_') or ref.startswith('narrative_sig_'):
            return signal_ref_map.get(ref, {}).get(account_id)

        # bare dec_XXXX_N  (V3 driver format without decision: prefix)
        if ref.startswith('dec_'):
            return decision_ref_map.get(ref, {}).get(account_id)

        # outcome by outcome_type fallback (e.g. "revenue_at_risk")
        nid = outcome_ref_map.get(ref, {}).get(account_id)
        if nid:
            return nid

        # Phased / recovery / CSM-action signal_ref keys (e.g. intervention_sig_415001_1,
        # baseline_narrative_sig_*, intervention_recovery_*). Prior narrow checks miss these.
        nid = signal_ref_map.get(ref, {}).get(account_id)
        if nid:
            return nid

        return None

    # ── 8. signal_edges.csv → context_edges (with ref resolution) ──
    edges_file = data_dir / 'signal_edges.csv'
    if edges_file.exists():
        try:
            df = pd.read_csv(edges_file)
            unresolved = 0
            with engine.begin() as conn:
                for _, row in df.iterrows():
                    from_ref = str(row.get('from_signal_ref', ''))
                    to_ref = str(row.get('to_signal_ref', ''))
                    rev_impact = None
                    try:
                        rev_impact = float(row.get('revenue_impact', 0))
                    except (ValueError, TypeError):
                        pass

                    props = _sanitize_props({
                        'from_signal_ref': from_ref,
                        'to_signal_ref': to_ref,
                        'evidence': row.get('evidence', ''),
                        'created_by': row.get('created_by', 'csv_import'),
                    })

                    _raw_etype = row.get('edge_type', 'CORRELATES_WITH')
                    if _raw_etype is None or (isinstance(_raw_etype, float) and pd.isna(_raw_etype)):
                        edge_type = 'CORRELATES_WITH'
                    else:
                        edge_type = str(_raw_etype).strip()

                    # If row has a specific account_id, resolve for that account only.
                    # Otherwise (arc-level edges), replicate for each account.
                    row_acct_id = None
                    for _col in ('account_id', 'source_account_id'):
                        _v = row.get(_col)
                        if _v is not None and not (isinstance(_v, float) and pd.isna(_v)):
                            try:
                                row_acct_id = int(float(_v))
                                break
                            except (ValueError, TypeError):
                                pass
                    acct_ids_to_resolve = [row_acct_id] if row_acct_id else sorted(all_account_ids)

                    for acct_id in acct_ids_to_resolve:
                        from_nid = _resolve_ref(from_ref, acct_id)
                        to_nid = _resolve_ref(to_ref, acct_id)

                        if from_nid and to_nid:
                            # ── Temporal validation: skip backward causal edges ──
                            if edge_type in ('LED_TO', 'TRIGGERED', 'CAUSED_BY'):
                                from_row = conn.execute(text(
                                    "SELECT occurred_at FROM context_nodes WHERE node_id = :nid"
                                ), {'nid': from_nid}).fetchone()
                                to_row = conn.execute(text(
                                    "SELECT occurred_at FROM context_nodes WHERE node_id = :nid"
                                ), {'nid': to_nid}).fetchone()
                                if (from_row and to_row
                                        and from_row[0] is not None and to_row[0] is not None
                                        and from_row[0] > to_row[0]):
                                    current_app.logger.warning(
                                        f"signal_edges: skipping backward {edge_type} edge "
                                        f"from_ref={from_ref!r} (occurred_at={from_row[0]}) "
                                        f"to_ref={to_ref!r} (occurred_at={to_row[0]}) "
                                        f"acct_id={acct_id}"
                                    )
                                    continue

                            conn.execute(text("""
                                INSERT INTO context_edges
                                    (customer_id, from_node_id, to_node_id,
                                     edge_type, weight, confidence,
                                     lag_days, revenue_impact, properties, source_platform)
                                VALUES
                                    (:cid, :from_nid, :to_nid,
                                     :etype, :weight, :conf,
                                     :lag, :rev, :props, :src)
                            """), {
                                'cid': customer_id,
                                'from_nid': from_nid,
                                'to_nid': to_nid,
                                'etype': edge_type,
                                'weight': float(row.get('weight', 0.5)),
                                'conf': float(row.get('confidence', 0.5)),
                                'lag': int(row.get('lag_days', 0)),
                                'rev': rev_impact,
                                'props': json.dumps(props),
                                'src': row.get('source_platform', 'csv_import'),
                            })
                            result['edges_inserted'] += 1
                        else:
                            # Log the exact ref that failed so diagnosis is immediate —
                            # None on from_nid = signal/decision ref not found in DB for this account
                            # None on to_nid   = decision/outcome ref not found in DB for this account
                            current_app.logger.warning(
                                f"signal_edges: unresolved ref "
                                f"acct_id={acct_id} edge_type={edge_type!r} | "
                                f"from_ref={from_ref!r} → node_id={from_nid} | "
                                f"to_ref={to_ref!r} → node_id={to_nid}"
                            )
                            unresolved += 1

            if unresolved:
                current_app.logger.warning(
                    f"signal_edges: {unresolved} edge-account pairs could not be resolved "
                    f"(see per-edge warnings above for exact refs)"
                )
            result['files_loaded'].append('signal_edges.csv')
            current_app.logger.info(
                f"✅ Loaded {result['edges_inserted']} signal edges "
                f"({len(df)} rows × {len(all_account_ids)} accounts, {unresolved} unresolved)"
            )
        except Exception as e:
            result['errors'].append(f"signal_edges.csv: {str(e)}")
            current_app.logger.error(f"Error loading signal_edges.csv: {e}", exc_info=True)

    # NOTE: SOURCED_FROM edges are now included in signal_edges.csv.
    # merged into signal_edges.csv by _auto_generate_context_graph_files() before
    # this function is called.

    # ── Wizard A: arc classification + context graph edge generation ──
    try:
        from wizards.wizard_a_journey_db import run_wizard_a
        wizard_a_result = run_wizard_a(customer_id)
        current_app.logger.info(
            f"Wizard A complete (post-ingest): "
            f"{wizard_a_result.get('processed', 0)} accounts, "
            f"{wizard_a_result.get('edges_created', 0)} edges created"
        )
        result['wizard_a'] = {
            'processed':     wizard_a_result.get('processed', 0),
            'edges_created': wizard_a_result.get('edges_created', 0),
            'arcs':          wizard_a_result.get('arcs', {}),
        }
    except Exception as _wa_err:
        current_app.logger.warning(
            f"Wizard A failed (non-fatal) in ingest_context_graph_csvs: {_wa_err}",
            exc_info=True,
        )

    # ------------------------------------------------------------------
    # Layer B2: Auto-generate INVOLVES edges (Stakeholder → Decision)
    # Links stakeholders to the decisions they influenced based on
    # decision_maker_role matching stakeholder node_subtype/title.
    # ------------------------------------------------------------------
    involves_created = 0
    try:
        involves_created = _auto_generate_involves_edges(customer_id, all_account_ids)
        if involves_created > 0:
            db.session.commit()
            current_app.logger.info(
                f"✅ Auto-generated {involves_created} INVOLVES edges "
                f"(stakeholder→decision) across {len(all_account_ids)} accounts"
            )
        result['involves_edges_created'] = involves_created
    except Exception as _inv_err:
        current_app.logger.warning(
            f"INVOLVES edge generation failed (non-fatal): {_inv_err}",
            exc_info=True,
        )
        db.session.rollback()

    # ------------------------------------------------------------------
    # Layer C: Urgent signal scanner — run per-account after edges are
    # committed so that to_node revenue_impact values are readable.
    # All errors are non-fatal; scanner result is appended to result dict.
    # ------------------------------------------------------------------
    urgent_alerts_total = 0
    try:
        from utils.urgent_signal_scanner import scan_for_urgent_signals
        from models import Account as _Account

        accounts_to_scan = _Account.query.filter_by(customer_id=customer_id).all()
        for _acct in accounts_to_scan:
            try:
                alerts = scan_for_urgent_signals(
                    customer_id=customer_id,
                    account_id=_acct.account_id,
                )
                urgent_alerts_total += len(alerts)
            except Exception as _ae:
                current_app.logger.debug(
                    f"urgent_signal_scanner: skipped account {_acct.account_id}: {_ae}"
                )

        if urgent_alerts_total:
            current_app.logger.info(
                f"urgent_signal_scanner: created {urgent_alerts_total} urgent alert(s) "
                f"for customer {customer_id}"
            )
    except Exception as _scanner_err:
        current_app.logger.warning(
            f"urgent_signal_scanner failed (non-fatal) for customer {customer_id}: {_scanner_err}"
        )

    result['urgent_alerts_created'] = urgent_alerts_total
    return result


